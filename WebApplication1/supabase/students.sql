-- Supabase schema for the Student CRUD.
-- Run this in the Supabase SQL editor before switching the app off the
-- in-memory repository.

create table if not exists public.students (
    id bigint generated by default as identity primary key,
    full_name text not null,
    email text not null unique,
    phone_number text,
    course text not null,
    enrollment_date date not null default current_date,
    gpa numeric(3, 2) check (gpa is null or (gpa >= 0 and gpa <= 4)),
    created_at timestamptz not null default now()
);

create index if not exists students_full_name_idx on public.students (full_name);

alter table public.students enable row level security;

-- Demo policies only. They let the anon key read and write, which is fine for
-- local development but must be tightened before going to production.
create policy "students_select_anon"
    on public.students for select
    to anon
    using (true);

create policy "students_insert_anon"
    on public.students for insert
    to anon
    with check (true);

create policy "students_update_anon"
    on public.students for update
    to anon
    using (true)
    with check (true);

create policy "students_delete_anon"
    on public.students for delete
    to anon
    using (true);
